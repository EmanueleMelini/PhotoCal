#!/usr/bin/env python3
"""
Generates app/src/main/assets/off_additives.tsv from the Open Food Facts additives taxonomy
(https://static.openfoodfacts.org/data/taxonomies/additives.json).

For every food additive (E number) the table has its parent (e.g. e322 for e322i), the risk
of overexposure from the EFSA re-evaluations as recorded by Open Food Facts
(efsa_evaluation_overexposure_risk: high, moderate, no) and the Italian and English names.
An additive without its own evaluation takes the one of its closest evaluated ancestor:
e450i is a diphosphate like e450.

Data source: Open Food Facts, Open Database License (ODbL). Run it again to follow the
taxonomy updates; the output is committed.

Usage:  python3 tools/off/build_additives_table.py [--input additives.json]
"""
import argparse
import json
import pathlib
import re
import urllib.request

URL = "https://static.openfoodfacts.org/data/taxonomies/additives.json"
USER_AGENT = "PhotoKCal (personal Android app; additives table import)"

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "app/src/main/assets/off_additives.tsv"

COLUMNS = ["code", "parent", "risk", "name_it", "name_en"]
LANGUAGES = ["it", "en"]

# Only real E numbers: "en:e150d", "en:e1404", "en:e322i"
E_NUMBER = re.compile(r"^en:(e\d{3,4}[a-z]*)$")
# Names start with the E number: "E250 - Nitrito di sodio"
NAME_PREFIX = re.compile(r"^E\s?\d{3,4}[a-z()ivx]*\s*-\s*", re.IGNORECASE)
RISKS = {"en:high": "high", "en:moderate": "moderate", "en:no": "no"}


def load(path: pathlib.Path | None) -> dict:
    if path:
        return json.loads(path.read_text(encoding="utf-8"))
    request = urllib.request.Request(URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def code_of(tag: str) -> str | None:
    match = E_NUMBER.match(tag)
    return match.group(1) if match else None


def clean_name(name: str | None) -> str:
    if not name:
        return ""
    cleaned = NAME_PREFIX.sub("", name).strip()
    # Some names are only the E number again ("E621 - E 621", "E150d"): no real name
    if not cleaned or code_of("en:" + cleaned.lower().replace(" ", "")):
        return ""
    return cleaned.replace("\t", " ")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=pathlib.Path, help="taxonomy already downloaded")
    args = parser.parse_args()
    taxonomy = load(args.input)

    entries = {}
    for tag, data in taxonomy.items():
        code = code_of(tag)
        if not code:
            continue
        parents = [p for p in (code_of(t) for t in data.get("parents", [])) if p]
        names = data.get("name", {})
        entries[code] = {
            "parent": parents[0] if parents else "",
            "own_risk": RISKS.get(data.get("efsa_evaluation_overexposure_risk", {}).get("en", "")),
            **{f"name_{lang}": clean_name(names.get(lang)) for lang in LANGUAGES},
        }

    def risk_of(code: str, seen: frozenset = frozenset()) -> str:
        entry = entries.get(code)
        if not entry or code in seen:
            return ""
        return entry["own_risk"] or risk_of(entry["parent"], seen | {code})

    rows = []
    for code in sorted(entries):
        entry = entries[code]
        row = {"code": code, "parent": entry["parent"], "risk": risk_of(code),
               "name_it": entry["name_it"] or entry["name_en"], "name_en": entry["name_en"]}
        rows.append(row)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8") as out:
        out.write("# Source: Open Food Facts additives taxonomy (ODbL), EFSA overexposure risk; "
                  "generated by tools/off/build_additives_table.py\n")
        out.write("\t".join(COLUMNS) + "\n")
        for row in rows:
            out.write("\t".join(row[c] for c in COLUMNS) + "\n")
    counts = {r: sum(1 for row in rows if row["risk"] == r) for r in ("high", "moderate", "no")}
    print(f"Wrote {len(rows)} additives to {OUTPUT.relative_to(ROOT)}; risk: {counts}")


if __name__ == "__main__":
    main()
