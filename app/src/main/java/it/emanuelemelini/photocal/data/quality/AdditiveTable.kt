package it.emanuelemelini.photocal.data.quality

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/** Risk that some population groups exceed the acceptable daily intake, according to EFSA. */
enum class AdditiveRisk { HIGH, MODERATE, NONE }

/** Food additive from the Open Food Facts taxonomy. [code] is lowercase, e.g. "e322i". */
data class Additive(
    val code: String,
    /** Family the additive belongs to, e.g. "e322" for "e322i". */
    val parent: String?,
    val risk: AdditiveRisk,
    val nameIt: String?,
    val nameEn: String?,
)

/**
 * Additives with their EFSA risk (assets/off_additives.tsv, generated by
 * tools/off/build_additives_table.py). A few hundred rows: kept in memory.
 */
class AdditiveTable(private val context: Context) {

    private val additives: Map<String, Additive> by lazy {
        context.assets.open(ASSET).bufferedReader().useLines(AdditiveFile::parse)
    }

    suspend fun all(): Map<String, Additive> = withContext(Dispatchers.IO) { additives }

    private companion object {
        const val ASSET = "off_additives.tsv"
    }
}

/** Format of off_additives.tsv: comment lines, a header, then code, parent, risk, Italian and English name. */
object AdditiveFile {

    fun parse(lines: Sequence<String>): Map<String, Additive> = lines
        .filterNot { it.startsWith("#") || it.isBlank() }
        .drop(1) // header
        .mapNotNull(::parseLine)
        .associateBy { it.code }

    private fun parseLine(line: String): Additive? {
        val cols = line.split('\t')
        if (cols.size < COLUMN_COUNT || cols[0].isBlank()) return null
        return Additive(
            code = cols[0],
            parent = cols[1].ifBlank { null },
            risk = when (cols[2]) {
                "high" -> AdditiveRisk.HIGH
                "moderate" -> AdditiveRisk.MODERATE
                else -> AdditiveRisk.NONE
            },
            nameIt = cols[3].ifBlank { null },
            nameEn = cols[4].ifBlank { null },
        )
    }

    private const val COLUMN_COUNT = 5
}
